-- =====================================================================
-- 01_schema.sql  —  run as EXCAV
--   sqlplus excav@localhost:1521/FREEPDB1 @database/01_schema.sql
-- Tables, spatial metadata and spatial indexes.
-- All geometries: WGS84 (SRID 4326, geodetic), tolerance 0.05 m.
-- =====================================================================
WHENEVER SQLERROR EXIT SQL.SQLCODE
SET ECHO ON

CREATE TABLE agencies (
  id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code      VARCHAR2(20)  NOT NULL UNIQUE,
  name_ar   VARCHAR2(200) NOT NULL,
  name_en   VARCHAR2(200) NOT NULL
);

CREATE TABLE app_users (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      VARCHAR2(50)  NOT NULL UNIQUE,
  password_hash VARCHAR2(500) NOT NULL,
  role          VARCHAR2(20)  NOT NULL CHECK (role IN ('Applicant','Reviewer')),
  agency_id     NUMBER REFERENCES agencies(id)
);

CREATE TABLE excavations (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agency_id     NUMBER NOT NULL REFERENCES agencies(id),
  work_type     VARCHAR2(100) NOT NULL,
  width_m       NUMBER(6,2)   NOT NULL CHECK (width_m > 0),
  start_date    DATE NOT NULL,
  end_date      DATE NOT NULL,
  status        VARCHAR2(20) DEFAULT 'Pending' NOT NULL
                CHECK (status IN ('Pending','Approved','Rejected')),
  length_m      NUMBER(12,2),
  area_m2       NUMBER(14,2),
  notes         VARCHAR2(1000),
  review_note   VARCHAR2(1000),
  created_by    NUMBER REFERENCES app_users(id),
  created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  reviewed_by   NUMBER REFERENCES app_users(id),
  reviewed_at   TIMESTAMP,
  route_geom    SDO_GEOMETRY NOT NULL,   -- polyline (route)
  area_geom     SDO_GEOMETRY NOT NULL,   -- polygon (buffered route)
  CONSTRAINT chk_dates CHECK (end_date >= start_date)
);

CREATE TABLE sensitive_sites (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR2(200) NOT NULL,
  site_type   VARCHAR2(50)  NOT NULL,                -- School | Hospital
  source      VARCHAR2(20)  DEFAULT 'Seed' NOT NULL, -- Seed | ArcGIS
  external_id VARCHAR2(100),
  geom        SDO_GEOMETRY NOT NULL
);

CREATE TABLE paved_roads (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR2(200) NOT NULL,
  paved_date  DATE NOT NULL,
  geom        SDO_GEOMETRY NOT NULL
);

CREATE TABLE city_boundary (
  id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name  VARCHAR2(100) NOT NULL,
  geom  SDO_GEOMETRY NOT NULL
);

-- ---------------------------------------------------------------------
-- Spatial metadata: MUST exist before the spatial index is created.
-- Names are UPPERCASE. Dimensions are lon/lat in degrees; the tolerance
-- (0.05) is in metres because SRID 4326 is geodetic.
-- ---------------------------------------------------------------------
INSERT INTO user_sdo_geom_metadata (table_name, column_name, diminfo, srid) VALUES
 ('EXCAVATIONS', 'ROUTE_GEOM',
  SDO_DIM_ARRAY(SDO_DIM_ELEMENT('Longitude',-180,180,0.05), SDO_DIM_ELEMENT('Latitude',-90,90,0.05)), 4326);
INSERT INTO user_sdo_geom_metadata (table_name, column_name, diminfo, srid) VALUES
 ('EXCAVATIONS', 'AREA_GEOM',
  SDO_DIM_ARRAY(SDO_DIM_ELEMENT('Longitude',-180,180,0.05), SDO_DIM_ELEMENT('Latitude',-90,90,0.05)), 4326);
INSERT INTO user_sdo_geom_metadata (table_name, column_name, diminfo, srid) VALUES
 ('SENSITIVE_SITES', 'GEOM',
  SDO_DIM_ARRAY(SDO_DIM_ELEMENT('Longitude',-180,180,0.05), SDO_DIM_ELEMENT('Latitude',-90,90,0.05)), 4326);
INSERT INTO user_sdo_geom_metadata (table_name, column_name, diminfo, srid) VALUES
 ('PAVED_ROADS', 'GEOM',
  SDO_DIM_ARRAY(SDO_DIM_ELEMENT('Longitude',-180,180,0.05), SDO_DIM_ELEMENT('Latitude',-90,90,0.05)), 4326);
INSERT INTO user_sdo_geom_metadata (table_name, column_name, diminfo, srid) VALUES
 ('CITY_BOUNDARY', 'GEOM',
  SDO_DIM_ARRAY(SDO_DIM_ELEMENT('Longitude',-180,180,0.05), SDO_DIM_ELEMENT('Latitude',-90,90,0.05)), 4326);
COMMIT;

-- Spatial (R-tree, domain) indexes — used by SDO_RELATE / SDO_WITHIN_DISTANCE
CREATE INDEX excav_route_sidx ON excavations(route_geom)  INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;
CREATE INDEX excav_area_sidx  ON excavations(area_geom)   INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;
CREATE INDEX sens_geom_sidx   ON sensitive_sites(geom)    INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;
CREATE INDEX paved_geom_sidx  ON paved_roads(geom)        INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;
CREATE INDEX city_geom_sidx   ON city_boundary(geom)      INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;

-- Regular B-tree indexes for the temporal / status filters
CREATE INDEX excav_dates_idx  ON excavations(start_date, end_date);
CREATE INDEX excav_status_idx ON excavations(status);

SET ECHO OFF
PROMPT Schema created.
EXIT
